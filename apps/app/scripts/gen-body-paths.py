#!/usr/bin/env python3
"""Regenerates lib/body-paths.ts from a checkout of MuscleMap (MIT, Melih Colpan).

    python3 apps/app/scripts/gen-body-paths.py /path/to/MuscleMap > apps/app/lib/body-paths.ts

Reads Sources/MuscleMap/Data/{Male,Female}{Front,Back}Paths.swift and emits the
SVG path strings as TypeScript. Nothing else from MuscleMap is used.
"""
import json
import re
import sys

root = sys.argv[1].rstrip('/') if len(sys.argv) > 1 else 'MuscleMap'
data_dir = f'{root}/Sources/MuscleMap/Data/'
view_box = {
    'male': {'front': '0 95 727 1280', 'back': '718 95 727 1280'},
    'female': {'front': '0 0 650 1450', 'back': '823 0 650 1450'},
}  # from BodyViewBox in BodyPathData.swift

out = {}
for gender in ('male', 'female'):
    out[gender] = {}
    for side in ('front', 'back'):
        swift = open(f'{data_dir}{gender.capitalize()}{side.capitalize()}Paths.swift').read()
        parts = []
        for block in swift.split('BodyPartPathData(')[1:]:
            slug = re.search(r'slug:\s*\.(\w+)', block)
            if slug:
                parts.append({'slug': slug.group(1), 'd': re.findall(r'"([^"]+)"', block)})
        out[gender][side] = {'viewBox': view_box[gender][side], 'parts': parts}

print('''// Body outline paths for the Train tab muscle map.
//
// Derived from MuscleMap by Melih Colpan (https://github.com/melihcolpan/MuscleMap),
// MIT License, Copyright (c) 2026 Melih Colpan. The licence text is in
// THIRD_PARTY_NOTICES.md at the repo root. Generated by scripts/gen-body-paths.py;
// regenerate it rather than editing this file by hand.

export type BodyPart = { slug: string; d: string[] };
export type BodyView = { viewBox: string; parts: BodyPart[] };
export const BODY_PATHS: Record<'male' | 'female', Record<'front' | 'back', BodyView>> = ''' + json.dumps(out, separators=(',', ':')) + ';')
